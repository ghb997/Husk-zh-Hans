    /** Every preference shown on this group's screen, groups flattened (a category's header, then its items). */
    void huskFlatten(java.util.List<Preference> out) {
        for (Preference p : mPreferences) {
            if (!p.isVisible()) continue;
            out.add(p);
            if (p instanceof PreferenceGroup && ((PreferenceGroup) p).isOnSameScreenAsChildren()) ((PreferenceGroup) p).huskFlatten(out);
        }
    }
