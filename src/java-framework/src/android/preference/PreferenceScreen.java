package android.preference;

import android.app.Dialog;
import android.content.Context;
import android.content.DialogInterface;
import android.util.AttributeSet;
import android.view.View;
import android.view.ViewGroup;
import android.widget.AdapterView;
import android.widget.BaseAdapter;
import android.widget.ListAdapter;
import android.widget.ListView;
import java.util.ArrayList;

/** The root of a settings screen, or a screen inside one (opened in a dialog when tapped, as the platform's). */
@Deprecated
public final class PreferenceScreen extends PreferenceGroup implements AdapterView.OnItemClickListener, DialogInterface.OnDismissListener {
    private Adapter mAdapter;
    private ListView mList;
    private Dialog mDialog;

    public PreferenceScreen(Context context, AttributeSet attrs) { super(context, attrs, 0, 0); }

    /** The rows: every visible preference of this screen, categories flattened in. */
    final class Adapter extends BaseAdapter {
        final ArrayList<Preference> rows = new ArrayList<>();
        Adapter() { rebuild(); }
        void rebuild() { rows.clear(); huskFlatten(rows); }
        public int getCount() { return rows.size(); }
        public Object getItem(int i) { return rows.get(i); }
        public long getItemId(int i) { return i; }
        @Override public boolean isEnabled(int i) { Preference p = rows.get(i); return p.isSelectable() && !(p instanceof PreferenceCategory); }
        @Override public boolean areAllItemsEnabled() { return false; }
        public View getView(int i, View convert, ViewGroup parent) { return rows.get(i).getView(convert, parent); }
        @Override public void notifyDataSetChanged() { rebuild(); super.notifyDataSetChanged(); }
    }
    public ListAdapter getRootAdapter() { if (mAdapter == null) mAdapter = new Adapter(); return mAdapter; }
    protected ListAdapter onCreateRootAdapter() { return getRootAdapter(); }
    public void bind(ListView list) {
        mList = list;
        list.setOnItemClickListener(this);
        list.setAdapter(getRootAdapter());
        onAttachedToActivity();
    }
    public void onItemClick(AdapterView<?> parent, View view, int position, long id) {
        if (parent instanceof ListView) position -= ((ListView) parent).getHeaderViewsCount();
        Object item = getRootAdapter().getItem(position);
        if (item instanceof Preference) ((Preference) item).performClick(this);
    }
    @Override protected boolean isOnSameScreenAsChildren() { return false; }
    public Dialog getDialog() { return mDialog; }

    /** A screen inside a screen, tapped: its own list, in a full-screen dialog. */
    @Override protected void onClick() {
        if (getIntent() != null || getFragment() != null || getPreferenceCount() == 0) return;
        if (mDialog != null && mDialog.isShowing()) return;
        ListView list = new ListView(getContext());
        bind(list);
        mDialog = new Dialog(getContext(), android.R.style.Theme_DeviceDefault_NoActionBar);
        if (getTitle() != null) mDialog.setTitle(getTitle());
        mDialog.setContentView(list);
        mDialog.setOnDismissListener(this);
        mDialog.show();
    }
    public void onDismiss(DialogInterface d) { mDialog = null; }

    /** A preference changed how it looks, or a group what it holds: the screens showing it redraw. */
    static void huskRefresh(Preference p) {
        for (Preference q = p; q != null; q = q.getParent()) {
            if (q instanceof PreferenceScreen) {
                PreferenceScreen s = (PreferenceScreen) q;
                if (s.mAdapter != null) {
                    final Adapter a = s.mAdapter;
                    if (android.os.Looper.myLooper() == android.os.Looper.getMainLooper()) a.notifyDataSetChanged();
                    else new android.os.Handler(android.os.Looper.getMainLooper()).post(a::notifyDataSetChanged);
                }
            }
        }
    }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public void setDialogFitsSystemWindows(boolean p0) {}
    // ---- end of generated members
}
