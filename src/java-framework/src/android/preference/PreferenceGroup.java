    public boolean addPreference(Preference p) {
        if (mPreferences.contains(p)) return true;
        if (p.getOrder() == DEFAULT_ORDER) { if (mOrderingAsAdded) p.setOrder(mCurrentOrder++); }
        int at = Collections.binarySearch(mPreferences, p);
        if (at < 0) at = -at - 1;
        if (!onPrepareAddPreference(p)) return false;
        mPreferences.add(at, p);
        p.mParent = this;
        if (getPreferenceManager() != null) p.onAttachedToHierarchy(getPreferenceManager());
        if (mAttachedToActivity) p.onAttachedToActivity();
        notifyHierarchyChanged();
        return true;
    }
    public boolean removePreference(Preference p) {
        boolean r = mPreferences.remove(p);
        if (r) { p.onPrepareForRemoval(); p.mParent = null; notifyHierarchyChanged(); }
        return r;
    }
    public void removeAll() { for (Preference p : new ArrayList<>(mPreferences)) removePreference(p); }
    public Preference findPreference(CharSequence key) {
        if (key == null) return null;
        if (key.toString().equals(getKey())) return this;
        for (Preference p : mPreferences) {
            if (key.toString().equals(p.getKey())) return p;
            if (p instanceof PreferenceGroup) { Preference q = ((PreferenceGroup) p).findPreference(key); if (q != null) return q; }
        }
        return null;
    }
