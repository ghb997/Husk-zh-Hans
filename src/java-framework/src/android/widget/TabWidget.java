package android.widget;

import android.content.Context;
import android.graphics.drawable.Drawable;
import android.util.AttributeSet;
import android.view.View;

/** The row of a TabHost's tab indicators; the current one is selected, a tap on one switches to it. */
public class TabWidget extends LinearLayout implements View.OnFocusChangeListener {
    private TabHost mHost;
    private int mSelected = -1;
    private boolean mStripEnabled = true;

    public TabWidget(Context c) { this(c, null); }
    public TabWidget(Context c, AttributeSet a) { super(c, a); setOrientation(HORIZONTAL); }
    public TabWidget(Context c, AttributeSet a, int s) { super(c, a, s); setOrientation(HORIZONTAL); }
    public TabWidget(Context c, AttributeSet a, int s, int r) { super(c, a, s, r); setOrientation(HORIZONTAL); }

    void huskSetHost(TabHost h) { mHost = h; }
    void huskAddTab(View indicator) {
        final int index = getChildCount();
        LayoutParams lp = new LayoutParams(0, LayoutParams.MATCH_PARENT, 1f);
        indicator.setFocusable(true);
        indicator.setClickable(true);
        indicator.setOnClickListener(v -> { if (mHost != null) mHost.setCurrentTab(index); });
        addView(indicator, lp);
    }
    public View getChildTabViewAt(int index) { return getChildAt(index); }
    public int getTabCount() { return getChildCount(); }
    public void setCurrentTab(int index) {
        if (index < 0 || index >= getTabCount() || index == mSelected) return;
        if (mSelected >= 0 && mSelected < getTabCount()) getChildTabViewAt(mSelected).setSelected(false);
        mSelected = index;
        View v = getChildTabViewAt(index);
        v.setSelected(true);
        for (int i = 0; i < getTabCount(); i++) { View c = getChildTabViewAt(i); c.setAlpha(i == index ? 1f : 0.6f); }
    }
    public void focusCurrentTab(int index) { setCurrentTab(index); }
    public void setStripEnabled(boolean e) { mStripEnabled = e; invalidate(); }
    public boolean isStripEnabled() { return mStripEnabled; }
    public void setDividerDrawable(Drawable d) {} public void setDividerDrawable(int r) {}
    public void setLeftStripDrawable(Drawable d) {} public void setLeftStripDrawable(int r) {}
    public void setRightStripDrawable(Drawable d) {} public void setRightStripDrawable(int r) {}
    public Drawable getLeftStripDrawable() { return null; } public Drawable getRightStripDrawable() { return null; }
    public void onFocusChange(View v, boolean hasFocus) {}
    @Override public void setEnabled(boolean e) { super.setEnabled(e); for (int i = 0; i < getTabCount(); i++) getChildTabViewAt(i).setEnabled(e); }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public void onInitializeAccessibilityEventInternal(android.view.accessibility.AccessibilityEvent p0) {}
    // ---- end of generated members
}
